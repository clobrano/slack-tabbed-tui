// Command gen writes table.go from iamcal/emoji-data's emoji.json, the
// dataset Slack's emoji names come from:
//
//	git clone --depth 1 --filter=blob:none --sparse https://github.com/iamcal/emoji-data
//	(cd emoji-data && git sparse-checkout set --no-cone /emoji.json)
//	go run ./internal/emoji/gen emoji-data/emoji.json > internal/emoji/table.go
package main

import (
	"encoding/json"
	"fmt"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	Unified     string   `json:"unified"`
	ShortNames  []string `json:"short_names"`
	SortOrder   int      `json:"sort_order"`
	ObsoletedBy string   `json:"obsoleted_by"`
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: gen emoji.json")
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var all []entry
	if err := json.Unmarshal(data, &all); err != nil {
		log.Fatal(err)
	}
	sort.Slice(all, func(i, j int) bool { return all[i].SortOrder < all[j].SortOrder })
	fmt.Println("// Code generated by internal/emoji/gen from iamcal/emoji-data (MIT); DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package emoji")
	fmt.Println()
	fmt.Println("// table lists the standard emoji in Slack's order: each name, then its")
	fmt.Println("// aliases, with the emoji.")
	fmt.Println("var table = []Emoji{")
	for _, e := range all {
		if e.ObsoletedBy != "" || len(e.ShortNames) == 0 {
			continue
		}
		var b strings.Builder
		for _, cp := range strings.Split(e.Unified, "-") {
			n, err := strconv.ParseUint(cp, 16, 32)
			if err != nil {
				log.Fatal(err)
			}
			b.WriteRune(rune(n))
		}
		for _, name := range e.ShortNames {
			fmt.Printf("\t{%q, %q},\n", name, b.String())
		}
	}
	fmt.Println("}")
}
